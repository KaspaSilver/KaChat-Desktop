    const close = el("button", { type: "button", "aria-label": "Dismiss", text: "×" });
    const hint = el("div", { class: "kom-hint", role: "note" },
      el("div", {}, `Coming from ${oldAddressLabel(cfg)}? `, el("a", { href: oldUrl, target: "_blank", rel: "noopener", text: "Open it there" }), " and press ", el("b", { text: "Move my accounts" }), "."),
      close);
    close.addEventListener("click", () => { hint.remove(); clearInterval(poll); try { storage.setItem(HINT_DISMISSED_KEY, "1"); } catch { /* fine */ } });
