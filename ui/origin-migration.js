/** Old side of the hand-off. Must run inside the click (window.open needs the user gesture). */
function startMove(cfg, { setStatus, buttons }) {
  const popup = window.open(`${newAddressUrl(cfg)}?migrate=1`, "kachat-desktop-move");
  if (!popup) { setStatus("Your browser blocked the new window. Allow pop-ups for kachat.app and press the button again.", true); return; }
  buttons.forEach((b) => { b.disabled = true; });
  setStatus(`Waiting for ${hostOf(cfg.to)} to open…`);
  let phase = "ready"; // ready -> sending -> ack -> done
  let nonce = null;
  let expectedHash = null;
  let snapshotCounts = null;
  const finish = (message, isError) => {
    window.removeEventListener("message", onMessage);
    clearInterval(watch);
    clearTimeout(readyTimer);
    buttons.forEach((b) => { b.disabled = false; });
    if (message) setStatus(message, isError);
  };
  const onMessage = async (event) => {
    if (phase === "ready") {
      const ready = validateReadyMessage(event, { expectedOrigin: cfg.to, popup });
      if (!ready.ok) return;
      phase = "sending";
      nonce = ready.nonce;
      clearTimeout(readyTimer);
      setStatus("Collecting your accounts…");
      try {
        const { snapshot, skipped } = await collectSnapshot();
        const chars = snapshotChars(snapshot);
        if (chars > MAX_PAYLOAD_CHARS) { finish(`Your KaChat data (${formatSize(chars)}) is larger than one move can carry. Remove old chat media in Settings and try again.`, true); return; }
        expectedHash = hashSnapshot(snapshot);
        snapshotCounts = { localStorage: snapshot.localStorage.length, chatStore: snapshot.chatStore.length, skipped };
        popup.postMessage({ type: MSG_DATA, v: PROTOCOL_VERSION, nonce, snapshot }, cfg.to);
        phase = "ack";
        setStatus(`Sent. Confirm the move in the ${hostOf(cfg.to)} window.`);
      } catch (error) {
        finish(`Could not read your KaChat data: ${error?.message || error}`, true);
      }
      return;
    }
    if (phase === "ack") {
      const result = validateAckMessage(event, { expectedOrigin: cfg.to, popup, nonce });
      if (!result.ok) return;
      const { ack } = result;
      if (!ack.ok) {
        phase = "done";
        finish(ack.reason === "declined" ? "The move was cancelled in the new window. Nothing changed here." : `The new address could not store your data${ack.message ? `: ${ack.message}` : "."} Nothing changed here.`, true);
        return;
      }
      if (ack.hash !== expectedHash) { phase = "done"; finish("The new address stored something different from what was sent. Nothing was marked as moved; please try again.", true); return; }
      phase = "done";
      const marker = { to: cfg.to, at: Date.now(), hash: expectedHash, counts: { ...snapshotCounts, accounts: Number(ack.counts?.accounts) || 0 } };
      try { globalThis.localStorage.setItem(MIGRATED_MARKER_KEY, JSON.stringify(marker)); } catch { /* shown anyway */ }
      finish();
      await unregisterServiceWorkers();
      showOldMoved(cfg, marker);
      document.querySelector("#kom-root .kom-status")?.replaceChildren(`Done. Your accounts are at ${hostOf(cfg.to)}.`);
    }
  };
  window.addEventListener("message", onMessage);
  const watch = setInterval(() => {
    if (phase !== "done" && popup.closed) { phase = "done"; finish("The new window was closed before the move finished. Nothing changed here.", true); }
  }, 500);
  const readyTimer = setTimeout(() => {
    if (phase === "ready") { phase = "done"; finish(`${hostOf(cfg.to)} did not answer. Check that it opens in your browser, then try again.`, true); }
  }, READY_TIMEOUT_MS);
}

