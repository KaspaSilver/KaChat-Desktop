// One-time move of KaChat Desktop from https://kachat.app/desktop/ to its own origin,
// https://desktop.kachat.app/ (audit DSK-013).
//
// Browser storage belongs to an origin, not a path, so while the wallet lived at kachat.app/desktop/
// every other page and service on kachat.app (the link site, the relay sidecar) could read its
// localStorage and IndexedDB. The wallet now has an origin of its own; this module carries the
// existing users' data across once, with a postMessage hand-off between the two exact origins.
//
// Roles (decided from location alone, before the app touches storage):
//   old  location.origin === MIGRATE_FROM and the path is under MIGRATE_FROM_PATH (/desktop/).
//        The app does not start. With saved accounts: "KaChat Desktop has moved" + "Move my
//        accounts". Without: a plain notice that forwards to the new address. After a move: the
//        moved screen, a link, and "Remove KaChat data from the old address".
//   new  location.origin === MIGRATE_TO. With ?migrate=1 and a window.opener: the receiving
//        screen (the app does not start until the data is written and the page reloads). Opened
//        directly with no accounts yet: the normal app plus a small "Coming from kachat.app/desktop?"
//        hint.
//   none any other origin (the test site, self-hosted installs, localhost): nothing happens.
//
// Hand-off protocol (version 1). Nothing travels in a URL; every postMessage names its exact
// targetOrigin and every listener checks event.origin AND event.source:
//   1. old: window.open(MIGRATE_TO + "/?migrate=1")                          (user click)
//   2. new -> old  { type: "kachat-migrate-ready", v: 1, nonce }      nonce = 32 random bytes, hex,
//                  generated by the new origin; resent every second until data arrives.
//   3. old -> new  { type: "kachat-migrate-data", v: 1, nonce, snapshot }    sent ONCE, echoing
//                  the nonce; snapshot = { localStorage: [[key, value]], chatStore: [[key, value]] }
//                  as stored - nothing is decrypted, sealed records stay sealed.
//   4. new: validates (origin, source, nonce, shapes, size), shows what arrived and asks the user
//      to confirm, replaces this origin's KaChat data with it, reads it back and hashes it.
//   5. new -> old  { type: "kachat-migrate-ack", v: 1, nonce, ok, hash, counts } (or ok:false,
//                  reason). The old origin compares the hash with its own hash of what it sent;
//                  only an exact match marks it migrated. The new page then reloads into the app.
//
// What moves: every localStorage key of the app (all start with "kachat") except caches the app
// rebuilds by itself (the same families Settings > Cache lists, plus node registries and the
// .kachat registry cache), and every entry of the IndexedDB chat store ("kachat-desktop" / "kv",
// see ui/storage.js). sessionStorage (the per-tab unlock hand-off) never moves: the user signs in
// again on the new address with the same password. Service-worker caches, notification permission
// and the installed web app are per origin and do not move either.

